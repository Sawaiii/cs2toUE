def say(text: str) -> None:
    """The installer is a windowed exe, so stdout can be missing entirely."""
    try:
        if sys.stdout is not None:
            sys.stdout.write(text + "\n")
            sys.stdout.flush()
    except Exception:
        pass


def run_silent(argv):
    target = default_target()
    shortcuts = True
    tools = True
    log = None
    for i, arg in enumerate(argv):
        if arg.startswith("--target="):
            target = Path(arg.split("=", 1)[1])
        elif arg == "--target" and i + 1 < len(argv):
            target = Path(argv[i + 1])
        elif arg == "--no-shortcuts":
            shortcuts = False
        elif arg == "--no-tools":
            tools = False
        elif arg.startswith("--log="):
            log = Path(arg.split("=", 1)[1])
    say(f"installing to {target}")
    try:
        dest = install(target, shortcuts, shortcuts)
    except Exception as exc:
        say(f"failed: {exc}")
        if log:
            log.write_text(f"failed: {exc}\n", encoding="utf-8")
        return 1
    result = f"installed: {dest}"
    if tools:
        say("downloading HLAE and Source 2 Viewer")
        got = download_tools(dest, say)
        result += "\ntools: " + ("downloaded" if got else "not downloaded, will be fetched later")
    say(result)
    if log:
        log.write_text(result + "\n", encoding="utf-8")
    return 0


def force_utf8() -> None:
    """Make output readable no matter what code page the machine uses."""
    os.environ.setdefault("PYTHONUTF8", "1")
    for stream in (sys.stdout, sys.stderr):
        try:
            if stream is not None:
                stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass
    try:
        import ctypes
        ctypes.windll.kernel32.SetConsoleOutputCP(65001)
        ctypes.windll.kernel32.SetConsoleCP(65001)
    except Exception:
        pass


def main():
    force_utf8()
    argv = sys.argv[1:]
    if "--silent" in argv or "/S" in argv:
        return run_silent(argv)
    run_gui()
    return 0


if __name__ == "__main__":
    sys.exit(main())
