"""cs2toUE-Setup.exe - the one and only installer.

The whole application is packed inside this file. It asks for a folder, copies the
program there, makes the shortcuts and registers an uninstall entry, all per user and
without administrator rights.

    cs2toUE-Setup.exe                       window
    cs2toUE-Setup.exe --silent [--target D:\\path] [--no-shortcuts]
"""

import os
import shutil
import subprocess
import sys
import winreg
from pathlib import Path

APP = "cs2toUE"
VERSION = "1.0.6"
REG_UNINSTALL = r"Software\Microsoft\Windows\CurrentVersion\Uninstall\cs2toUE"


def payload_dir() -> Path:
    """The bundled copy of the application."""
    base = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent))
    for candidate in (base / "app", base / "dist" / APP):
        if (candidate / "cs2toUE.exe").is_file():
            return candidate
    return base / "app"


def default_target() -> Path:
    """The usual place for a per-user Windows program: %LOCALAPPDATA%\\Programs\\cs2toUE.

    Not C:\\Program Files, because that folder needs administrator rights - and the
    program keeps its workspace (HLAE builds, converted maps, exported scenes) next to
    itself, so it has to be able to write there. The folder is a free choice in the
    installer, and any drive works.
    """
    local = os.environ.get("LOCALAPPDATA")
    if local:
        return Path(local) / "Programs" / APP
    return Path(os.environ.get("ProgramFiles", "C:\\Program Files")) / APP


def free_gb(path) -> float:
    try:
        return shutil.disk_usage(Path(path).drive + "\\").free / 1024 ** 3
    except OSError:
        return -1.0


def payload_size(src: Path) -> int:
    return sum(p.stat().st_size for p in src.rglob("*") if p.is_file())


# ------------------------------------------------------------------ install

def copy_app(src: Path, dest: Path, progress=None) -> None:
    files = [p for p in src.rglob("*") if p.is_file()]
    dest.mkdir(parents=True, exist_ok=True)
    for i, item in enumerate(files, 1):
        target = dest / item.relative_to(src)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, target)
        if progress and (i % 20 == 0 or i == len(files)):
            progress(i / len(files), item.name)


def _powershell(script: str) -> None:
    """Run a script through a file, never through -Command.

    A command line with non-ASCII characters goes through the console code page of the
    machine, which turns Cyrillic into mojibake on a differently localised Windows. A
    UTF-8 file with a BOM is read correctly by PowerShell everywhere.
    """
    tmp = Path(os.environ.get("TEMP", ".")) / "cs2toue_setup_step.ps1"
    try:
        tmp.write_text(script, encoding="utf-8-sig")
        subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                        "-File", str(tmp)],
                       creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0), check=False)
    except Exception:
        pass
    finally:
        try:
            tmp.unlink()
        except OSError:
            pass


def make_shortcut(link: Path, target: Path, workdir: Path, description: str) -> None:
    link.parent.mkdir(parents=True, exist_ok=True)
    script = (
        "$s=(New-Object -ComObject WScript.Shell).CreateShortcut('{}');"
        "$s.TargetPath='{}';$s.WorkingDirectory='{}';$s.Description='{}';$s.Save()".format(
            link, target, workdir, description)
    )
    _powershell(script)


def create_shortcuts(dest: Path, desktop: bool = True, start_menu: bool = True) -> None:
    exe = dest / "cs2toUE.exe"
    if start_menu:
        group = Path(os.environ["APPDATA"]) / r"Microsoft\Windows\Start Menu\Programs" / APP
        make_shortcut(group / f"{APP}.lnk", exe, dest, "CS2 demo to Unreal Engine")
        make_shortcut(group / "РЈРґР°Р»РёС‚СЊ cs2toUE.lnk", dest / "Uninstall.cmd", dest,
                      "Uninstall cs2toUE")
    if desktop:
        desk = Path(os.path.expanduser("~")) / "Desktop"
        if not desk.is_dir():
            desk = Path(os.environ.get("USERPROFILE", ".")) / "Desktop"
        make_shortcut(desk / f"{APP}.lnk", exe, dest, "CS2 demo to Unreal Engine")


UNINSTALL_CMD = """@echo off
rem Removes cs2toUE. Generated by the installer.
echo Removing cs2toUE from "{dest}"
echo.
reg delete "HKCU\\{reg}" /f >nul 2>&1
del /q "%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\{app}\\*.lnk" >nul 2>&1
rmdir "%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\{app}" >nul 2>&1
del /q "%USERPROFILE%\\Desktop\\{app}.lnk" >nul 2>&1
echo The workspace folder is NOT deleted automatically - it holds the HLAE builds,
echo converted maps and exported scenes you may still want:
echo     "{dest}\\workspace"
echo.
echo Delete the program folder by hand to finish.
pause
"""


def write_uninstaller(dest: Path) -> None:
    (dest / "Uninstall.cmd").write_text(
        UNINSTALL_CMD.format(dest=dest, reg=REG_UNINSTALL, app=APP), encoding="utf-8")


def register(dest: Path, size_kb: int) -> None:
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, REG_UNINSTALL) as key:
        values = {
            "DisplayName": f"{APP} - CS2 demo to Unreal Engine",
            "DisplayVersion": VERSION,
            "Publisher": APP,
            "InstallLocation": str(dest),
            "DisplayIcon": str(dest / "cs2toUE.exe"),
            "UninstallString": f'"{dest / "Uninstall.cmd"}"',
        }
        for name, value in values.items():
            winreg.SetValueEx(key, name, 0, winreg.REG_SZ, value)
        winreg.SetValueEx(key, "EstimatedSize", 0, winreg.REG_DWORD, size_kb)
        winreg.SetValueEx(key, "NoModify", 0, winreg.REG_DWORD, 1)
        winreg.SetValueEx(key, "NoRepair", 0, winreg.REG_DWORD, 1)


def download_tools(dest: Path, status=None, timeout: int = 900) -> bool:
    """Pull HLAE and the Source 2 Viewer CLI right away.

    They are not baked into the installer on purpose: the right HLAE build depends on
    which CS2 patch the machine has, and both tools get new releases constantly. Doing
    it here means the program is complete once the installer finishes.
    """
    exe = dest / "cs2toue-cli.exe"
    if not exe.is_file():
        return False
    try:
        proc = subprocess.Popen(
            [str(exe), "prefetch"], cwd=str(dest),
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, encoding="utf-8", errors="replace",
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except OSError:
        return False
    try:
        for line in proc.stdout:
            line = line.strip()
            if line and status:
                status(line[:90])
        proc.wait(timeout=timeout)
    except Exception:
        proc.kill()
        return False
    return proc.returncode == 0


def install(target, desktop=True, start_menu=True, progress=None):
    src = payload_dir()
    if not (src / "cs2toUE.exe").is_file():
        raise RuntimeError(f"the installer payload is missing ({src})")
    dest = Path(target)
    need = payload_size(src)
    have = free_gb(dest)
    # half a gigabyte of headroom: HLAE, maps and exported scenes land next to the program
    if 0 <= have < (need / 1024 ** 3 + 0.5):
        raise RuntimeError(
            f"РќР° РґРёСЃРєРµ {dest.drive} РЅРµРґРѕСЃС‚Р°С‚РѕС‡РЅРѕ РјРµСЃС‚Р°: СЃРІРѕР±РѕРґРЅРѕ {have:.1f} Р“Р‘, "
            f"РЅСѓР¶РЅРѕ {need / 1024 ** 2:.0f} РњР‘ РЅР° РїСЂРѕРіСЂР°РјРјСѓ Рё Р·Р°РїР°СЃ РїРѕРґ СЃРєР°С‡РёРІР°РµРјС‹Рµ С„Р°Р№Р»С‹.\n\n"
            f"Р’С‹Р±РµСЂРёС‚Рµ РґСЂСѓРіСѓСЋ РїР°РїРєСѓ вЂ” РїРѕРґРѕР№РґС‘С‚ Р»СЋР±РѕР№ РґРёСЃРє."
        )
    copy_app(src, dest, progress)
    write_uninstaller(dest)
    if desktop or start_menu:
        create_shortcuts(dest, desktop, start_menu)
    register(dest, int(need / 1024))
    return dest


